#!/usr/bin/env python3
"""
R3: Blog Content Generator (Multi-Provider Fallback)
Purpose: Generate 800-1500 word blog posts with problem-solution-buying guide structure
Input: Blog title (from R2), trending keywords (from R13), current topic
Output: Complete blog post content with internal link placeholders
Frequency: Every 6 hours (after R2 completes)
Dependencies: R2 (provides title), R13 (provides keywords)

Provider Chain: Groq → Gemini → Cohere → OpenAI
ROBUST FALLBACK: If one provider fails, automatically tries next provider
"""

import os
import sys
import mysql.connector
from datetime import datetime
import logging
import traceback

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

BOLD = '\033[1m'
RESET = '\033[0m'
GREEN = '\033[92m'
RED = '\033[91m'
YELLOW = '\033[93m'
BLUE = '\033[94m'

class BlogContentGenerator:
    def __init__(self):
        """Initialize content generator with multi-provider API support"""
        # Check available API keys - all optional since we have a fallback chain
        self.groq_key = os.getenv("GROQ_API_KEY")
        self.gemini_key = os.getenv("GEMINI_API_KEY")
        self.cohere_key = os.getenv("COHERE_API_KEY")
        self.openai_key = os.getenv("OPENAI_API_KEY")

        # Model names - FROM ENVIRONMENT VARIABLES (flexible, accepts any model)
        self.groq_model = os.getenv("GROQ_MODEL")
        self.gemini_model = os.getenv("GEMINI_MODEL")
        self.cohere_model = os.getenv("COHERE_MODEL")
        self.openai_model = os.getenv("OPENAI_MODEL")

        # Check that at least ONE API key is available
        if not any([self.groq_key, self.gemini_key, self.cohere_key, self.openai_key]):
            logger.error("CRITICAL: No API keys found!")
            logger.error("At least one of these must be set:")
            logger.error("  - GROQ_API_KEY")
            logger.error("  - GEMINI_API_KEY")
            logger.error("  - COHERE_API_KEY")
            logger.error("  - OPENAI_API_KEY")
            sys.exit(1)

        # Log which providers are available
        if self.groq_key:
            logger.info("✓ GROQ_API_KEY is set")
        else:
            logger.warning("⚠ GROQ_API_KEY not set - will skip Groq provider")

        if self.gemini_key:
            logger.info("✓ GEMINI_API_KEY is set")
        else:
            logger.warning("⚠ GEMINI_API_KEY not set - will skip Gemini provider")

        if self.cohere_key:
            logger.info("✓ COHERE_API_KEY is set")
        else:
            logger.warning("⚠ COHERE_API_KEY not set - will skip Cohere provider")

        if self.openai_key:
            logger.info("✓ OPENAI_API_KEY is set")
        else:
            logger.warning("⚠ OPENAI_API_KEY not set - will skip OpenAI provider")

        self.provider_used = None

        self.db_config = {
            'host': os.getenv('DB_HOST', 'localhost'),
            'user': os.getenv('DB_USER', 'root'),
            'password': os.getenv('DB_PASSWORD', ''),
            'database': os.getenv('DB_NAME', 'ghgf_blogging')
        }

        self.content_generated = False
        self.content_length = 0

    def print_header(self, title):
        """Print formatted header"""
        print(f"\n{'='*70}")
        print(f"{BOLD}{title}{RESET}")
        print('='*70)

    def connect_db(self):
        """Connect to database"""
        try:
            conn = mysql.connector.connect(**self.db_config)
            logger.info("Database connected successfully")
            return conn
        except Exception as e:
            logger.error(f"Database connection failed: {str(e)}")
            return None

    def get_best_title(self, conn):
        """Get the best title generated by R2"""
        try:
            cursor = conn.cursor(dictionary=True)
            # Get highest scored title from last 24 hours
            query = """
                SELECT id, title, topic, keywords
                FROM blog_titles
                WHERE used = FALSE
                AND created_at > DATE_SUB(NOW(), INTERVAL 24 HOUR)
                ORDER BY ctr_score DESC
                LIMIT 1
            """
            cursor.execute(query)
            result = cursor.fetchone()
            cursor.close()

            if result:
                logger.info(f"Retrieved title: {result['title']}")
                return result
            else:
                logger.error("No available titles from R2")
                return None
        except Exception as e:
            logger.error(f"Error getting title: {str(e)}")
            return None

    def get_keywords_for_content(self, conn, topic):
        """Get top 8 keywords for content generation"""
        try:
            cursor = conn.cursor(dictionary=True)
            query = """
                SELECT keyword, search_volume
                FROM trending_keywords
                WHERE topic = %s
                ORDER BY search_volume DESC
                LIMIT 8
            """
            cursor.execute(query, (topic,))
            results = cursor.fetchall()
            cursor.close()

            if results:
                logger.info(f"Retrieved {len(results)} keywords for content")
                return results
            return []
        except Exception as e:
            logger.error(f"Error getting keywords: {str(e)}")
            return []

    def get_prompt(self, title, keywords, topic):
        """Generate the shared prompt for all providers"""
        keywords_str = ", ".join([f"{k['keyword']}" for k in keywords[:5]])

        # Create keyword injection points - emphasize keywords multiple times
        keyword_injection = "\n".join([f"- '{k['keyword']}' - use 3-4 times throughout the post" for k in keywords[:5]])

        prompt = f"""Write a comprehensive, engaging health/fitness blog post with the title: "{title}"

STRUCTURE (MUST follow this format):
1. Introduction (150-200 words): Hook the reader, explain why this matters, INCLUDE the keywords naturally and prominently
2. Problem Section (200-250 words): Discuss the main problem/challenge related to the topic, USE keywords to describe the problem
3. Solution/How-To Section (300-350 words): Provide 3-4 actionable solutions or steps, EMPHASIZE keywords when describing solutions
4. Benefits Section (150-200 words): Explain the benefits of following this advice, HIGHLIGHT how keywords lead to benefits
5. Buying Guide Section (150-200 words): Recommend 2-3 types of products/solutions (leave space for [[AFFILIATE_LINK]] placeholders), MENTION keywords in product descriptions
6. Conclusion (100-150 words): Summarize, call to action, REINFORCE the keywords as key takeaways

CRITICAL KEYWORD REQUIREMENTS:
{keyword_injection}

REQUIREMENTS:
- Total length: 800-1500 words
- Write in HTML format with proper tags: <h2>, <h3>, <p>, <ul>, <li> - ALL TAGS MUST BE PROPERLY CLOSED
- CRITICAL: Each keyword MUST appear 3-4 times naturally throughout the post (1% keyword density minimum)
- Age-appropriate for all ages (avoid overly technical jargon)
- Medically accurate (include disclaimers like "consult a doctor")
- Add internal link placeholders: [[INTERNAL_LINK:related_topic]]
- Add affiliate link placeholders: [[AFFILIATE_LINK:product_type]]
- Include practical tips and actionable advice
- Use short paragraphs (2-3 sentences max)
- Include at least 2 lists/bullet points
- Professional, friendly tone
- ENSURE EVERY OPENING TAG HAS A CLOSING TAG (balanced HTML)

Topic: {topic}
Keywords to naturally include (use 3-4 times each): {keywords_str}

Return ONLY the HTML content, no explanations or markdown."""
        return prompt

    def generate_content_groq(self, title, keywords, topic):
        """Generate blog content using Groq"""
        if not self.groq_key:
            logger.debug("Groq API key not available, skipping Groq provider")
            return None

        try:
            from groq import Groq

            logger.info("=" * 70)
            logger.info("ATTEMPTING GROQ PROVIDER")
            logger.info("=" * 70)

            client = Groq(api_key=self.groq_key)
            prompt = self.get_prompt(title, keywords, topic)

            logger.info(f"Calling Groq API with model: {self.groq_model}")
            response = client.chat.completions.create(
                model=self.groq_model,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=2000,
                temperature=0.7
            )

            if response.choices and response.choices[0].message.content:
                content = response.choices[0].message.content.strip()
                self.content_generated = True
                self.content_length = len(content)
                self.provider_used = "Groq"
                logger.info(f"✓ Groq succeeded: {self.content_length} characters")
                return content
            else:
                logger.error("Groq returned empty response")
                return None
        except ImportError:
            logger.warning("Groq library not installed, skipping Groq provider")
            return None
        except Exception as e:
            logger.error(f"GROQ PROVIDER FAILED: {type(e).__name__}: {str(e)}")
            logger.debug(f"Traceback: {traceback.format_exc()}")
            return None

    def generate_content_gemini(self, title, keywords, topic):
        """Fallback: Generate content using Google Gemini"""
        if not self.gemini_key:
            logger.debug("Gemini API key not available, skipping Gemini provider")
            return None

        try:
            import google.generativeai as genai

            logger.info("=" * 70)
            logger.info("ATTEMPTING GEMINI PROVIDER")
            logger.info("=" * 70)

            genai.configure(api_key=self.gemini_key)
            prompt = self.get_prompt(title, keywords, topic)

            logger.info(f"Calling Google Gemini API with model: {self.gemini_model if self.gemini_model else '(default)'}")

            if self.gemini_model:
                model = genai.GenerativeModel(self.gemini_model)
            else:
                model = genai.GenerativeModel()

            response = model.generate_content(prompt)

            if response.text:
                content = response.text
                self.content_generated = True
                self.content_length = len(content)
                self.provider_used = "Gemini"
                logger.info(f"✓ Gemini succeeded: {self.content_length} characters")
                return content
            else:
                logger.error("Gemini returned empty response")
                return None
        except ImportError:
            logger.warning("Google Generative AI library not installed, skipping Gemini provider")
            return None
        except Exception as e:
            logger.error(f"GEMINI PROVIDER FAILED: {type(e).__name__}: {str(e)}")
            logger.debug(f"Traceback: {traceback.format_exc()}")
            return None

