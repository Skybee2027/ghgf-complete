#!/usr/bin/env python3
"""
R3: Blog Content Generator
Purpose: Generate 800-1500 word blog posts with problem-solution-buying guide structure
Input: Blog title (from R2), trending keywords (from R13), current topic
Output: Complete blog post content with internal link placeholders
Frequency: Every 6 hours (after R2 completes)
Dependencies: R2 (provides title), R13 (provides keywords)
"""

import os
import sys
import mysql.connector
from datetime import datetime
from groq import Groq
import logging

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

BOLD = '\033[1m'
RESET = '\033[0m'
GREEN = '\033[92m'
RED = '\033[91m'
YELLOW = '\033[93m'
BLUE = '\033[94m'

class BlogContentGenerator:
    def __init__(self):
        """Initialize content generator"""
        self.groq_key = os.getenv("GROQ_API_KEY")
        self.gemini_key = os.getenv("GEMINI_API_KEY")  # Google Gemini API key

        # Use environment variable driven models - flexible, accepts any model
        self.groq_model = os.getenv("GROQ_MODEL")
        self.gemini_model = os.getenv("GEMINI_MODEL")

        if not self.groq_key:
            logger.error("GROQ_API_KEY not set")
            sys.exit(1)

        self.db_config = {
            'host': os.getenv('DB_HOST', 'localhost'),
            'user': os.getenv('DB_USER', 'root'),
            'password': os.getenv('DB_PASSWORD', ''),
            'database': os.getenv('DB_NAME', 'ghgf_blogging')
        }

        self.content_generated = False
        self.content_length = 0

    def print_header(self, title):
        """Print formatted header"""
        print(f"\n{'='*70}")
        print(f"{BOLD}{title}{RESET}")
        print('='*70)

    def connect_db(self):
        """Connect to database"""
        try:
            conn = mysql.connector.connect(**self.db_config)
            logger.info("Database connected successfully")
            return conn
        except Exception as e:
            logger.error(f"Database connection failed: {str(e)}")
            return None

    def get_best_title(self, conn):
        """Get the best title generated by R2"""
        try:
            cursor = conn.cursor(dictionary=True)
            # Get highest scored title from last 24 hours
            query = """
                SELECT id, title, topic, keywords
                FROM blog_titles
                WHERE used = FALSE
                AND created_at > DATE_SUB(NOW(), INTERVAL 24 HOUR)
                ORDER BY ctr_score DESC
                LIMIT 1
            """
            cursor.execute(query)
            result = cursor.fetchone()
            cursor.close()

            if result:
                logger.info(f"Retrieved title: {result['title']}")
                return result
            else:
                logger.error("No available titles from R2")
                return None
        except Exception as e:
            logger.error(f"Error getting title: {str(e)}")
            return None

    def get_keywords_for_content(self, conn, topic):
        """Get top 8 keywords for content generation"""
        try:
            cursor = conn.cursor(dictionary=True)
            query = """
                SELECT keyword, search_volume
                FROM trending_keywords
                WHERE topic = %s
                ORDER BY search_volume DESC
                LIMIT 8
            """
            cursor.execute(query, (topic,))
            results = cursor.fetchall()
            cursor.close()

            if results:
                logger.info(f"Retrieved {len(results)} keywords for content")
                return results
            return []
        except Exception as e:
            logger.error(f"Error getting keywords: {str(e)}")
            return []

    def generate_content_groq(self, title, keywords, topic):
        """Generate blog content using Groq"""
        try:
            client = Groq(api_key=self.groq_key)

            keywords_str = ", ".join([f"{k['keyword']}" for k in keywords[:5]])

            prompt = f"""Write a comprehensive, engaging health/fitness blog post with the title: "{title}"

STRUCTURE (MUST follow this format):
1. Introduction (150-200 words): Hook the reader, explain why this matters, mention the keywords naturally
2. Problem Section (200-250 words): Discuss the main problem/challenge related to the topic
3. Solution/How-To Section (300-350 words): Provide 3-4 actionable solutions or steps
4. Benefits Section (150-200 words): Explain the benefits of following this advice
5. Buying Guide Section (150-200 words): Recommend 2-3 types of products/solutions (leave space for [[AFFILIATE_LINK]] placeholders)
6. Conclusion (100-150 words): Summarize, call to action, encourage reader engagement

REQUIREMENTS:
- Total length: 800-1500 words
- Write in HTML format with proper tags: <h2>, <h3>, <p>, <ul>, <li>
- Use keyword naturally: {keywords_str}
- Age-appropriate for all ages (avoid overly technical jargon)
- Medically accurate (include disclaimers like "consult a doctor")
- Add internal link placeholders: [[INTERNAL_LINK:related_topic]]
- Add affiliate link placeholders: [[AFFILIATE_LINK:product_type]]
- Include practical tips and actionable advice
- Use short paragraphs (2-3 sentences max)
- Include at least 2 lists/bullet points
- Professional, friendly tone

Topic: {topic}
Keywords to naturally include: {keywords_str}

Return ONLY the HTML content, no explanations."""

            # Groq REQUIRES model parameter - use env var or default
            logger.info(f"Calling Groq API with model: {self.groq_model}")
            response = client.chat.completions.create(
                model=self.groq_model,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=2000,
                temperature=0.7
            )

            if response.choices and response.choices[0].message.content:
                content = response.choices[0].message.content.strip()
                self.content_generated = True
                self.content_length = len(content)
                logger.info(f"Content generated: {self.content_length} characters")
                return content
            else:
                logger.error("Groq returned empty response")
                return None
        except Exception as e:
            logger.error(f"Groq API error: {str(e)}")
            return None

    def generate_content_google(self, title, keywords, topic):
        """Fallback: Generate content using Google Gemini"""
        try:
            import google.generativeai as genai
            genai.configure(api_key=self.gemini_key)

            keywords_str = ", ".join([f"{k['keyword']}" for k in keywords[:5]])

            prompt = f"""Write a comprehensive health blog post: "{title}"
Topic: {topic}
Keywords: {keywords_str}
Length: 800-1500 words
Include: introduction, problem, solution, benefits, buying guide, conclusion
Format in HTML with <h2>, <h3>, <p>, <ul>, <li> tags
Add [[INTERNAL_LINK:topic]] and [[AFFILIATE_LINK:product]] placeholders"""

            # Gemini model is optional - use env var if set, otherwise omit
            if self.gemini_model:
                logger.info(f"Calling Google Gemini API with model: {self.gemini_model}")
                model = genai.GenerativeModel(self.gemini_model)
            else:
                logger.info("Calling Google Gemini API with default model")
                model = genai.GenerativeModel()

            response = model.generate_content(prompt)

            if response.text:
                content = response.text
                self.content_generated = True
                self.content_length = len(content)
                logger.info(f"Content generated (Google): {self.content_length} characters")
                return content
            return None
        except Exception as e:
            logger.error(f"Google API error: {str(e)}")
            return None

    def validate_content(self, content):
        """Validate generated content quality"""
        issues = []

        # Check length
        if len(content) < 800:
            issues.append(f"Content too short: {len(content)} chars (minimum 800)")
        elif len(content) > 2000:
            logger.warning(f"Content longer than expected: {len(content)} chars")

        # Check structure
        required_tags = ['<h2>', '<p>', '</p>']
        for tag in required_tags:
            if tag not in content:
                issues.append(f"Missing required HTML tag: {tag}")

        # Check placeholders
        if '[[AFFILIATE_LINK' not in content:
            issues.append("Missing affiliate link placeholders")

        if issues:
            logger.warning(f"Content validation warnings: {issues}")
            return False, issues

        return True, []

    def save_content_to_db(self, conn, content, title_data):
        """Save generated content to blog_posts table"""
        try:
            cursor = conn.cursor()

            query = """
                INSERT INTO blog_posts (title_id, title, content, topic, status, ready_for_wordpress, final_qa_passed, version, created_at)
                VALUES (%s, %s, %s, %s, 'draft', TRUE, TRUE, 1, NOW())
            """
            cursor.execute(query, (
                title_data['id'],
                title_data['title'],
                content,
                title_data['topic']
            ))

            blog_id = cursor.lastrowid

            # Mark title as used
            update_query = "UPDATE blog_titles SET used = TRUE, used_at = NOW() WHERE id = %s"
            cursor.execute(update_query, (title_data['id'],))

            # Create initial version record
            version_query = """
                INSERT INTO version_history (blog_id, version, content, robot_modified_by, change_type, created_at)
                VALUES (%s, 1, %s, 'R3', 'initial', NOW())
            """
            cursor.execute(version_query, (blog_id, content))

            conn.commit()
            logger.info(f"Content saved to database with blog_id: {blog_id}")
            return blog_id
        except Exception as e:
            logger.error(f"Error saving content: {str(e)}")
            return None
        finally:
            cursor.close()

    def run(self):
        """Main execution flow"""
        self.print_header("R3: BLOG CONTENT GENERATOR")
        print(f"Execution: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")

        # Connect to database
        conn = self.connect_db()
        if not conn:
            logger.error("Cannot proceed without database connection")
            return False

        try:
            # Step 1: Get best title from R2
            print(f"{BOLD}Step 1: Retrieving Best Title from R2{RESET}")
            title_data = self.get_best_title(conn)
            if not title_data:
                logger.error("Failed to get title from R2")
                return False
            print(f"  ✓ Title: {BLUE}{title_data['title']}{RESET}")
            print(f"  ✓ Topic: {title_data['topic']}\n")

            # Step 2: Get keywords for content
            print(f"{BOLD}Step 2: Retrieving Keywords from R13 Cache{RESET}")
            keywords = self.get_keywords_for_content(conn, title_data['topic'])
            if keywords:
                for kw in keywords[:5]:
                    print(f"  • {kw['keyword']}")
            print()

            # Step 3: Generate content using Groq
            print(f"{BOLD}Step 3: Generating Blog Content (via Groq){RESET}")
            content = self.generate_content_groq(title_data['title'], keywords, title_data['topic'])

            if not content:
                logger.warning("Groq generation failed, trying Google Gemini...")
                content = self.generate_content_google(title_data['title'], keywords, title_data['topic'])

            if not content:
                logger.error("Failed to generate content from all APIs")
                return False

            print(f"  ✓ {GREEN}Content generated: {self.content_length} characters{RESET}\n")

            # Step 4: Validate content
            print(f"{BOLD}Step 4: Validating Content Quality{RESET}")
            is_valid, issues = self.validate_content(content)
            if is_valid:
                print(f"  ✓ {GREEN}Content validation passed{RESET}")
            else:
                print(f"  ⚠ {YELLOW}Content validation warnings:{RESET}")
                for issue in issues:
                    print(f"    - {issue}")
            print()

            # Step 5: Save to database
            print(f"{BOLD}Step 5: Saving to Database{RESET}")
            blog_id = self.save_content_to_db(conn, content, title_data)
            if not blog_id:
                return False
            print(f"  ✓ {GREEN}Content saved with blog_id: {blog_id}{RESET}\n")

            # Summary
            print(f"{'='*70}")
            print(f"{BOLD}SUMMARY{RESET}")
            print(f"  Title: {BLUE}{title_data['title']}{RESET}")
            print(f"  Blog ID: {BLUE}{blog_id}{RESET}")
            print(f"  Topic: {title_data['topic']}")
            print(f"  Content Length: {GREEN}{self.content_length} characters{RESET}")
            print(f"  Keywords Used: {len(keywords)}")
            print(f"  Status: {GREEN}SUCCESS - Ready for R4 (Plagiarism Check){RESET}")
            print('='*70 + "\n")

            return True

        except Exception as e:
            logger.error(f"Unexpected error: {str(e)}")
            return False
        finally:
            conn.close()

if __name__ == "__main__":
    generator = BlogContentGenerator()
    success = generator.run()
    sys.exit(0 if success else 1)
